"""Compare the .con contracts of several games/mods (the JSON files inventory.py writes).

    python3 -I python/tools/contract_diff.py data/out/contract --base bf1942 \
        --corpora bf1942 xpack1 xpack2 dc07 dcfinal gc --out data/out/contract/summary.md

The summary says what each corpus needs beyond the base game: the extra the interpreter and the
simulation have to cover for that mod to work.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load(d: Path, name: str) -> dict:
    return json.loads((d / f"{name}.json").read_text(encoding="utf-8"))


def printable(text: str) -> str:
    """Scripts carry binary junk (a corrupt .con in GC); keep the Markdown plain text."""
    return "".join(c if c.isprintable() or c == "\n" else "?" for c in text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("dir", type=Path)
    ap.add_argument("--base", required=True)
    ap.add_argument("--corpora", nargs="+", required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    data = {n: load(a.dir, n) for n in a.corpora}
    base = data[a.base]

    md = ["# `.con` contracts compared", "",
          f"Generated by `python/tools/contract_diff.py` with base `{a.base}`. Do not edit by hand.", ""]
    md += ["| corpus | files | lines | commands | types | `run` | `if` | `while` | `var`/`const` | `run` resolution |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for n, j in data.items():
        k = j["keywords"]
        res = ", ".join(f"{h} {c}" for h, c in sorted(j["run_resolution"].items()))
        md.append(f"| {n} | {j['files']} | {j['lines']} | {len(j['commands'])} | {len(j['creates'])} | "
                  f"{k.get('run', 0)} | {k.get('if', 0)} | {k.get('while', 0)} | {k.get('var', 0) + k.get('const', 0)} | {res} |")

    all_cmds = set().union(*(j["commands"] for j in data.values()))
    md += ["", f"Union of commands: **{len(all_cmds)}**. Union of types: "
           f"**{len(set().union(*(j['creates'] for j in data.values())))}**.", ""]

    for n, j in data.items():
        if n == a.base:
            continue
        new_types = sorted(set(j["creates"]) - set(base["creates"]))
        new_cmds = sorted(set(j["commands"]) - set(base["commands"]), key=lambda c: (-j["commands"][c], c))
        new_props = {}
        for t, props in j["props"].items():
            extra = sorted(set(props) - set(base["props"].get(t, {})))
            if extra:
                new_props[t] = extra
        md += [f"## {n} against {a.base}", ""]
        md += [f"- New types ({len(new_types)}): " + (", ".join(f"`{t}`" for t in new_types) or "none")]
        md += [f"- Conditions: " + (", ".join(f"`{c}`×{v}" for c, v in j["conditions"].items()) or "none")]
        md += [f"- Commands {a.base} does not use ({len(new_cmds)}), by use:", ""]
        md += ["  " + ", ".join(f"`{c}`×{j['commands'][c]}" for c in new_cmds[:80]) + (" …" if len(new_cmds) > 80 else ""), ""]
        if new_props:
            md += ["- New properties on types that already exist:", ""]
            for t, props in sorted(new_props.items(), key=lambda kv: (-len(kv[1]), kv[0]))[:25]:
                md += [f"  - `{t}`: " + ", ".join(f"`{p}`" for p in props)]
            md += [""]
    a.out.write_text(printable("\n".join(md) + "\n"), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
