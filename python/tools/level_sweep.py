"""Load every level in every game mode of every mod with `con load`, and summarise.

    python3 -I python/tools/level_sweep.py data/game --mods bf1942 XPack1 XPack2 DC_Final GCMOD \
        --out data/out/contract/levels.md

The interpreter's progress report: what still fails, per mod, and why. A diagnostic here is
either a gap in bytefield (to fix) or a defect in the data that the original also had (to tolerate,
and listed as known gaps in the project notes).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CON = ROOT / "target" / "release" / "con-check"


def printable(text: str) -> str:
    return "".join(c if c.isprintable() or c == "\n" else "?" for c in text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("game", type=Path)
    ap.add_argument("--mods", nargs="+", required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()

    md = ["# Level sweep", "", "Generated by `python/tools/level_sweep.py`: `con load` of each level in each mode. Do not edit by hand.", ""]
    md += ["Columns: **no interpreter errors** = nothing bytefield does not know how to do (command error, "
           "bad condition, unimplemented keyword). The rest are defects in the data that the original has too: "
           "references to templates or scripts that do not exist, commands with typos that the engine ignores "
           "(`remObjectTemplate.x`, `//ObjectTemplate.x`) and junk lines.", ""]
    md += ["| mod | loads | no interpreter errors | instances without template | `run` not found | ignored (typos) | interpreter errors | junk lines |",
           "|---|---|---|---|---|---|---|---|"]
    details = []
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "r.json"
        for mod in a.mods:
            levels = subprocess.run([CON, "levels", a.game, mod], capture_output=True, text=True, check=True).stdout.splitlines()
            loads = clean = 0
            missing_inst, missing_run, cmd_err, ignored, stray = Counter(), Counter(), Counter(), Counter(), 0
            failures = []
            for row in levels:
                level, _, modes = row.partition("\t")
                for mode in filter(None, modes.split(",")):
                    p = subprocess.run([CON, "load", a.game, mod, "--level", level, "--mode", mode, "--json", out], capture_output=True, text=True)
                    loads += 1
                    if p.returncode != 0:
                        failures.append(f"{level}/{mode}: {p.stderr.strip()}")
                        continue
                    r = json.loads(out.read_text())
                    kinds = dict(r["diagnostics_by_kind"])
                    stray += kinds.get("StrayLine", 0)
                    for t, n in r["missing_instance_templates"].items():
                        missing_inst[f"{level}: {t}"] += n
                    for d in r["diagnostics"]:
                        if d["kind"] == "MissingScript":
                            missing_run[f"{d['file']}: {d['text']}"] += 1
                        elif d["kind"] == "UnknownCommand":
                            ignored[d["text"][:80]] += 1
                        elif d["kind"] in ("CommandError", "BadCondition", "Unsupported", "Recursion"):
                            cmd_err[f"{d['kind']} {d['text'][:80]}"] += 1
                    if not set(kinds) & {"CommandError", "BadCondition", "Unsupported", "Recursion"}:
                        clean += 1
            md.append(f"| {mod} | {loads} | {clean} | {sum(missing_inst.values())} | {len(missing_run)} | {sum(ignored.values())} | {sum(cmd_err.values())} | {stray} |")
            details += [f"## {mod}", ""]
            if failures:
                details += ["Loads that fail:", "", *[f"- {f}" for f in failures], ""]
            for title, c in (("Interpreter errors", cmd_err), ("Instances without template", missing_inst),
                             ("`run` not found", missing_run), ("Ignored commands (typos)", ignored)):
                if c:
                    details += [f"{title}:", "", *[f"- {k} ×{n}" for k, n in c.most_common(40)], ""]
            print(f"{mod}: {clean}/{loads} clean")
    a.out.write_text(printable("\n".join(md + [""] + details) + "\n"), encoding="utf-8")


if __name__ == "__main__":
    main()
