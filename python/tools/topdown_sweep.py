"""Run `topdown` on every level of some mods and summarise the layout checks.

    python3 -I python/tools/topdown_sweep.py data/game --mods bf1942 XPack1 XPack2 DC_Final \
        --out data/out/contract/topdown.md --images out/topdown

Each level answers three questions (see crates/world/src/bin/topdown.rs): which way the
heightmap maps onto x/z (objects must sit on it), and which way the level's ingamemap.dds is
drawn, against the colour tiles and against the water. The conclusion is the majority, and the
levels that disagree are the ones to look at.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BIN = ROOT / "target" / "release"


def best(scores):
    if not scores:
        return None, None, None
    s = sorted(scores, key=lambda x: -x["score"])
    return s[0]["orientation"], s[0]["score"], s[0]["score"] - (s[1]["score"] if len(s) > 1 else 0)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("game", type=Path)
    ap.add_argument("--mods", nargs="+", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--images", type=Path, required=True)
    a = ap.parse_args()

    rows, votes = [], {"heightmap": Counter(), "tiles": Counter(), "water": Counter()}
    for mod in a.mods:
        levels = subprocess.run([BIN / "con-check", "levels", a.game, mod], capture_output=True, text=True, check=True).stdout.splitlines()
        for row in levels:
            level, _, modes = row.partition("\t")
            mode = (modes.split(",") or ["conquest"])[0] or "conquest"
            out = a.images / mod / level
            p = subprocess.run([BIN / "topdown", a.game, mod, level, out, "--mode", mode], capture_output=True, text=True)
            if p.returncode != 0:
                rows.append(f"| {mod} | {level} | fails: {p.stderr.strip()[:80]} | | | | |")
                continue
            r = json.loads((out / "report.json").read_text())
            h, hs, hm = best(r["objects_on_terrain"])
            t, ts, tm = best(r["tiles_vs_ingamemap"])
            w, ws, wm = best(r["water_vs_ingamemap"])
            offset = r["tex_offset"] != [0.0, 0.0]
            if hm is not None and hm >= 0.05:
                votes["heightmap"][h] += 1
            if t and tm >= 0.05 and not offset:
                votes["tiles"][t] += 1
            if w and wm >= 0.05:
                votes["water"][w] += 1
            fmt = lambda o, s, m: f"{o} {s:.2f} (±{m:.2f})" if o else "—"
            rows.append(f"| {mod} | {level} | {fmt(h, hs, hm)} | {r['objects_median_residual_m']:.2f} | "
                        f"{fmt(t, ts, tm)}{' (texOffset)' if offset else ''} | {fmt(w, ws, wm)} | {r['placed']} |")
            print(rows[-1])

    md = ["# Layout of terrain, tiles and ingamemap", "",
          "Generated by `python/tools/topdown_sweep.py` (the `topdown` tool). Do not edit by hand.", "",
          "Votes (only levels with margin ≥ 0.05; the tiles, only without `texOffset`):", ""]
    for k, c in votes.items():
        md.append(f"- **{k}**: " + ", ".join(f"{o} ×{n}" for o, n in c.most_common()))
    md += ["", "| mod | level | heightmap: % objects within <1 m | median (m) | ingamemap vs tiles (r) | ingamemap vs water (r) | objects |",
           "|---|---|---|---|---|---|---|", *rows]
    a.out.write_text("\n".join(md) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
