"""Inventory of the .con scripts of a game or mod: the contract the interpreter has to cover.

    uv run python -I tools/inventory.py ../data/mods/gc-src/src --name gc --out ../data/out/contract

Writes <out>/<name>.md (to read) and <out>/<name>.json (to diff: between mods, and against the
Rust interpreter in F2). The data is read as untrusted input: nothing in it is executed.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # -I drops the script dir

from bytefield_tools.con_scan import Inventory, scan, spelling, to_json, type_spelling  # noqa: E402


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _shapes(inv: Inventory, low: str, n: int = 3) -> str:
    parts = []
    for shape, count in inv.shapes[low].most_common(n):
        parts.append(f"`{' '.join(shape) or '—'}`×{count}")
    return ", ".join(parts)


def render(inv: Inventory, name: str, root: str) -> str:
    md = [f"# `.con` contract: {name}", ""]
    md += [f"Generated by `python/tools/inventory.py` over `{root}`. Do not edit by hand.", ""]
    md += [f"- Files: **{inv.files}**, lines with a command: **{inv.lines}**",
           f"- Distinct commands: **{len(inv.commands)}** in **{len({c.split('.')[0] for c in inv.commands})}** namespaces",
           f"- Template types created: **{len(inv.creates)}**",
           f"- `run`/`include`: **{inv.run_targets}**; found by " + ", ".join(
               f"{how}: **{n}**" for how, n in sorted(inv.run_resolution.items())),
           "  (file = relative to the script, ancestor = relative to a parent directory, root = at the mod's root)",
           f"- Stray lines (neither command nor keyword): **{len(inv.stray)}**", ""]

    md += ["## Keywords and flow control", ""]
    md += _table(["word", "uses"], [[k, v] for k, v in inv.keywords.most_common()])
    md += ["", "Conditions:", ""]
    md += _table(["condition", "uses"], [[f"`{k}`", v] for k, v in inv.conditions.most_common()])

    md += ["", "## Namespaces", ""]
    ns_count: dict[str, list[int]] = {}
    for low, n in inv.commands.items():
        ns = low.split(".")[0]
        ns_count.setdefault(ns, [0, 0])
        ns_count[ns][0] += n
        ns_count[ns][1] += 1
    rows = sorted(ns_count.items(), key=lambda kv: -kv[1][0])
    md += _table(["namespace", "uses", "distinct commands"],
                 [[spelling(inv, next(c for c in inv.commands if c.split('.')[0] == ns)).split(".")[0], u, d]
                  for ns, (u, d) in rows])

    md += ["", "## Template types (`X.create <Type>`)", ""]
    md += _table(["namespace", "type", "created", "distinct properties"],
                 [[ns, type_spelling(inv, t), n, len(inv.props.get((ns, t), {}))]
                  for (ns, t), n in inv.creates.most_common()])

    md += ["", "## Properties per type", "",
           "What the simulation has to understand of each type. Argument shapes: "
           "`int`, `float`, `vecN` (`a/b/c`), `name`, `path` and `var` (`v_` variables and `c_` constants, like `c_ETPlane`).", ""]
    for (ns, t), props in sorted(inv.props.items(), key=lambda kv: -sum(kv[1].values())):
        md += [f"### {ns}: {type_spelling(inv, t)}", ""]
        md += _table(["property", "uses", "shapes"],
                     [[f"`{spelling(inv, f'{ns}.{m}')}`", c, _shapes(inv, f'{ns}.{m}')]
                      for m, c in props.most_common()])
        md += [""]

    md += ["## All commands", ""]
    md += _table(["command", "uses", "files", "shapes"],
                 [[f"`{spelling(inv, c)}`", n, len(inv.command_files[c]), _shapes(inv, c)]
                  for c, n in sorted(inv.commands.items())])

    if inv.no_active:
        md += ["", "## Properties with no active template in their file", "",
               "They depend on a `create`/`active` done in another file (the interpreter's global state).", ""]
        md += _table(["command", "uses"], [[f"`{spelling(inv, c)}`", n] for c, n in inv.no_active.most_common()])

    md += ["", "## Anomalies", "", f"### Stray lines ({len(inv.stray)})", "", "```"]
    md += inv.stray[:200] + (["..."] if len(inv.stray) > 200 else []) + ["```", ""]
    md += [f"### `run`/`include` not resolved on disk ({len(inv.run_unresolved)})", "",
           "Refractor also searches from the roots of the `.rfa` archives; this is a hint, not a sure error.", "", "```"]
    md += inv.run_unresolved[:200] + (["..."] if len(inv.run_unresolved) > 200 else []) + ["```", ""]
    return "\n".join(md)


def printable(text: str) -> str:
    """Scripts carry binary junk (a corrupt .con in GC); keep the Markdown plain text."""
    return "".join(c if c.isprintable() or c == "\n" else "?" for c in text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", type=Path, help="directory with the unpacked .con files")
    ap.add_argument("--name", required=True, help="label: vanilla, dc, gc...")
    ap.add_argument("--out", type=Path, default=Path("data/out/contract"))
    a = ap.parse_args()
    inv = scan(a.root)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / f"{a.name}.md").write_text(printable(render(inv, a.name, a.root.as_posix())), encoding="utf-8")
    (a.out / f"{a.name}.json").write_text(json.dumps(to_json(inv), indent=1, sort_keys=True), encoding="utf-8")
    print(f"{a.name}: {inv.files} files, {inv.lines} lines, {len(inv.commands)} commands, "
          f"{len(inv.creates)} types, {len(inv.stray)} stray, {len(inv.run_unresolved)} unresolved runs")


if __name__ == "__main__":
    main()
